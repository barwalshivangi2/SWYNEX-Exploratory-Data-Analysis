import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

df = pd.read_csv("cleaned_dataset.csv")

print(df.describe())

plt.figure(figsize=(14, 10))

plt.subplot(2, 2, 1)
sns.countplot(x='Survived', data=df, palette='Set2')
plt.title('Overall Survival')

plt.subplot(2, 2, 2)
sns.countplot(x='Survived', hue='Sex', data=df, palette='Set1')
plt.title('Survival by Gender')

plt.subplot(2, 2, 3)
sns.histplot(df['Age'], bins=20, kde=True, color='purple')
plt.title('Age Distribution')

plt.subplot(2, 2, 4)
sns.boxplot(x='Pclass', y='Fare', data=df, palette='pastel')
plt.title('Fare by Class')

plt.tight_layout()
plt.savefig('eda_charts.png')
plt.show()

print("\nInsights:")
print("1. Survival rate was low overall.")
print("2. Females survived more than males.")
print("3. Most passengers were aged 20-30.")
print("4. 1st class had better survival chances and higher fares.")
print("5. Fare column has extreme outliers.")